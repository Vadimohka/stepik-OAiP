#include <string>
#include <cassert>
int main() {

// тип string, операции над строками
std::string s1 = "s-1";
std::string s2 = "s-2";
std::string s3;
bool b;

// операция '=' (присваивание строк)
s3 = s1; // s3 = "s-1"

// операция '+' - конкатенация строк
s3 = s3 + s2; // s3 = "s-1s-2"

// операция '+=' - присваивание с конкатенацией
s3 = "s-3";
s3 += "abc"; // s3 = "s-3abc"

// операция '==' - сравнение строк
b = s2==s1; // b = false
b = s2=="s-2"; // b = true

// операция '!=' - сравнение строк (не равно)
s1 = "s1";
s2 = "s2";
b = s1 != s2; // b = true

// операции '<' и '>' - сравнение строк
s1 = "abcd";
s2 = "de";
b = s1 > s2; // b = false
b = s1 < s2; // b = true

// операции '<=' и '>=' - сравнение строк (меньше или равно, больше или равно)
s1 = "abcd";
s2 = "ab";
b = s1 >= s2; // b = true
b = s1 <= s2; // b = false
b = s2 >= "ab"; // b = true

// операция [] - индексация
char c;
s1 = "abcd";
c = s1[2]; // c = 'c'
c = s1[0]; // c = 'a'
assert(s1 == "abcd"); assert(s2 == "ab"); assert(b); assert(c == 'a');
}
