#!/usr/bin/env python3
"""Verify the complete 2026-11-23 revision using only the standard library.

No Stepik or network calls are made. A failed or interrupted run cannot retain a
successful aggregate result, and every nested report is regenerated by this run.
"""
from __future__ import annotations

import argparse
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
REVISION = ROOT / 'improvements/86957'
QUALITY = REVISION / 'quality-2026-11-23'
ASSESSMENT = REVISION / 'assessment-2026-11-23'
REPORT = REVISION / 'validation.json'
STANDARDS = ('c++17', 'c++20')
CONTAINER_FLAGS = ('-O2', '-Wall', '-Wextra', '-Wpedantic',
                   '-Wconversion', '-Wsign-conversion', '-Werror')


def read_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def inside(base: Path, name: str) -> Path:
    path = (base / name).resolve()
    require(path.is_relative_to(base.resolve()), f'Path escapes its directory: {name}')
    return path


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def input_hashes() -> dict[str, str]:
    paths = {ROOT / 'courses/86957/manifest.json',
             ROOT / 'tools/build_quality_packages.py', Path(__file__).resolve()}
    staged_ids = set()
    for package in (QUALITY, ASSESSMENT):
        paths.update(package / name for name in ('manifest.json', 'CHANGES.md', 'preview.html'))
        paths.update(package.glob('changes_*.json'))
        paths.update((package / 'steps').glob('*/*.step'))
        paths.update((package / 'baseline').glob('*/*.step'))
        for step in (package / 'steps').glob('*/*.step'):
            staged_ids.add(int(step.name.split('_')[1]))
        manifest = read_json(package / 'manifest.json')
        for entry in manifest['steps']:
            for field in ('source_path', 'target_path', 'baseline_path'):
                paths.add(inside(ROOT, entry[field]))
        for path in (package / 'examples').rglob('*'):
            if (path.is_file() and path.name != 'validation.json'
                    and path.suffix in {'.cpp', '.hpp', '.h', '.py', '.json'}
                    and not any(part.startswith('.') or part == '__pycache__'
                                for part in path.relative_to(package).parts)):
                paths.add(path)
        if (package / 'verify.py').exists():
            paths.add(package / 'verify.py')
    # The assessment also checks evidence in an unchanged ownership lesson.
    contexts = {sid for entry in read_json(ASSESSMENT / 'changes_assessment.json')['changes']
                for rationale in entry['rationales'] for sid in rationale['context_step_ids']}
    for sid in sorted(contexts - staged_ids):
        matches = list((ROOT / 'courses/86957/steps').glob(f'*/*_{sid}_*.step'))
        require(len(matches) == 1, f'Expected one source context for step {sid}')
        paths.add(matches[0])
    require(all(path.is_file() for path in paths), 'A required validation input is missing')
    return {path.relative_to(ROOT).as_posix(): digest(path) for path in sorted(paths)}


def run(command: list[str], stage: str, cwd: Path = ROOT, timeout: int = 300):
    completed = subprocess.run(command, cwd=cwd, text=True, encoding='utf-8',
                               capture_output=True, timeout=timeout)
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout).strip()[-1800:]
        raise RuntimeError(f'{stage} exited {completed.returncode}: {detail}')
    return completed


def nested_report(script: Path, arguments: list[str], report_path: Path,
                  hash_base: Path, name: str) -> dict:
    write_json(report_path, {'status': 'running', 'all_passed': False})
    run([sys.executable, str(script), *arguments], name)
    report = read_json(report_path)
    require(report.get('status') == 'passed' and report.get('all_passed') is True,
            f'{name}: report does not confirm success')
    recorded = report.get('input_sha256')
    require(isinstance(recorded, dict) and bool(recorded), f'{name}: missing input hashes')
    for name_in_report, expected in recorded.items():
        path = inside(hash_base, name_in_report)
        require(path.is_file() and digest(path) == expected,
                f'{name}: changed validation input {name_in_report}')
    return report


class CodeBlocks(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.capture = False
        self.parts = []
        self.blocks = []

    def handle_starttag(self, tag, attrs):
        if tag == 'code' and 'language-cpp' in dict(attrs).get('class', '').split():
            self.capture = True
            self.parts = []

    def handle_data(self, data):
        if self.capture:
            self.parts.append(data)

    def handle_endtag(self, tag):
        if tag == 'code' and self.capture:
            self.blocks.append(''.join(self.parts).rstrip('\n'))
            self.capture = False


def verify_embedded_examples(group: Path, steps: dict[int, Path]) -> list[dict]:
    examples = read_json(group / 'cases.json')['examples']
    sources = set()
    for example in examples:
        source = inside(group, example['source'])
        require(source not in sources, f'Duplicate example {source.name}')
        sources.add(source)
        require(example['step_id'] in steps, f'Missing context step for {source.name}')
        step = read_json(steps[example['step_id']])
        parser = CodeBlocks()
        parser.feed(step['block']['text'])
        require(source.read_text(encoding='utf-8').rstrip('\n') in parser.blocks,
                f'Compiled source differs from lesson HTML: {source.name}')
    require(sources == set(group.glob('*.cpp')), f'Unlisted C++ source in {group.name}')
    return examples


def container_checks(compiler: str, steps: dict[int, Path], temporary: Path) -> dict:
    group = QUALITY / 'examples/containers'
    examples = verify_embedded_examples(group, steps)
    require(len(examples) == 4 and sum(len(e['cases']) for e in examples) == 22,
            'Expected four container examples and 22 fixture cases')
    builds, cases = [], []
    for standard in STANDARDS:
        for example in examples:
            source = group / example['source']
            executable = temporary / (source.stem + '-' + standard)
            run([compiler, '-std=' + standard, *CONTAINER_FLAGS, str(source), '-o', str(executable)],
                f'compile {source.name} {standard}', timeout=60)
            builds.append({'source': example['source'], 'standard': standard})
            for case in example['cases']:
                with tempfile.TemporaryDirectory(dir=temporary) as folder:
                    work = Path(folder)
                    for name, content in case.get('files', {}).items():
                        path = inside(work, name)
                        path.parent.mkdir(parents=True, exist_ok=True)
                        path.write_bytes(content.encode('utf-8'))
                    completed = subprocess.run([str(executable)], cwd=work,
                                               input=case.get('stdin', ''), text=True,
                                               encoding='utf-8', capture_output=True, timeout=10)
                    expected = (case.get('returncode', 0), case['stdout'], case.get('stderr', ''))
                    actual = (completed.returncode, completed.stdout, completed.stderr)
                    require(actual == expected,
                            f'{source.name}/{standard}/{case["name"]}: {actual!r} != {expected!r}')
                    for name, content in case.get('expected_files', {}).items():
                        require(inside(work, name).read_bytes() == content.encode('utf-8'),
                                f'{source.name}/{case["name"]}: wrong output file {name}')
                    for name in case.get('expected_absent', []):
                        require(not inside(work, name).exists(), f'Unexpected output file {name}')
                cases.append({'source': example['source'], 'standard': standard,
                              'case': case['name'], 'passed': True})
    return {'name': 'containers', 'status': 'passed', 'compilations': len(builds),
            'runtime_cases': len(cases), 'subset_checks': 0, 'flags': list(CONTAINER_FLAGS),
            'builds': builds, 'checks': cases}


def validate(compiler: str, result: dict) -> None:
    before = input_hashes()
    result['input_sha256'] = before
    version = run([compiler, '--version'], 'compiler version', timeout=20).stdout.splitlines()
    require(bool(version), 'Compiler did not report its version')
    result['compiler'] = version[0]
    run([sys.executable, str(ROOT / 'tools/build_quality_packages.py'), '--check'],
        'package artifact check')
    result['stages'].append({'name': 'package_artifacts', 'status': 'passed'})

    steps = {}
    for path in (QUALITY / 'steps').glob('*/*.step'):
        sid = int(read_json(path)['id'])
        require(sid not in steps, f'Duplicate quality step ID {sid}')
        steps[sid] = path
    verify_embedded_examples(QUALITY / 'examples/algorithms', steps)
    algorithms_path = QUALITY / 'examples/algorithms'
    algorithms = nested_report(algorithms_path / 'verify.py',
        ['--compiler', compiler, '--report', str(algorithms_path / 'validation.json')],
        algorithms_path / 'validation.json', algorithms_path, 'algorithms')
    require(all(row['passed'] is True for row in algorithms['results']), 'Algorithm result failed')
    algorithm_runs = sum(row['fixed_cases'] + row['generated_cases'] for row in algorithms['results'])
    require(algorithms['program_runs'] == algorithm_runs, 'Algorithm run count mismatch')
    result['stages'].append({'name': 'algorithms', 'status': 'passed',
        'compilations': len(algorithms['results']), 'runtime_cases': algorithm_runs, 'subset_checks': 0})

    files_path = QUALITY / 'examples/files'
    files = nested_report(files_path / 'verify.py',
        ['--compiler', compiler, '--output', str(files_path / 'validation.json')],
        files_path / 'validation.json', QUALITY, 'files')
    require(all(row['passed'] is True for row in files['checks']), 'File-I/O result failed')
    require(files['cases'] == len(files['checks']), 'File-I/O run count mismatch')
    file_builds = len({(row['source'], row['standard']) for row in files['checks']})
    result['stages'].append({'name': 'files', 'status': 'passed', 'compilations': file_builds,
        'runtime_cases': files['cases'], 'subset_checks': 0})

    assessments = nested_report(ASSESSMENT / 'verify.py',
        ['--cxx', compiler, '--report', str(ASSESSMENT / 'validation.json')],
        ASSESSMENT / 'validation.json', ROOT, 'assessments')
    require(all(row['exit_code'] == 0 for row in assessments['cpp_example']), 'Assessment C++ run failed')
    result['stages'].append({'name': 'assessments', 'status': 'passed',
        'compilations': len(assessments['cpp_example']), 'runtime_cases': len(assessments['cpp_example']),
        'subset_checks': assessments['local_truth_table_subsets'] + assessments['permuted_truth_table_subsets'],
        'context_evidence_checks': assessments['context_evidence_checks']})

    with tempfile.TemporaryDirectory(prefix='.quality-check-', dir=REVISION) as folder:
        result['stages'].append(container_checks(compiler, steps, Path(folder)))
    after = input_hashes()
    require(after == before, 'Validation inputs changed during the run; rebuild and rerun')
    for field in ('compilations', 'runtime_cases', 'subset_checks', 'context_evidence_checks'):
        result[field] = sum(stage.get(field, 0) for stage in result['stages'])
    result['quality_steps'] = len(steps)
    result['assessment_steps'] = len(list((ASSESSMENT / 'steps').glob('*/*.step')))
    result['status'], result['all_passed'] = 'passed', True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', default='g++', help='C++ compiler executable')
    args = parser.parse_args()
    result = {'schema_version': 1, 'course_id': 86957, 'date': '2026-11-23',
              'status': 'running', 'all_passed': False, 'standards': list(STANDARDS),
              'stages': [],
              'limitations': ['Validated on Linux; Windows/MSVC was not run.',
                              'No Stepik publication, live rendering or platform grading was performed.',
                              'The assessment subset checks verify stored author keys, not Stepik scoring.',
                              'Hardware failures and a full disk were not injected.']}
    write_json(REPORT, result)
    try:
        validate(args.compiler, result)
    except Exception as error:
        result['status'], result['all_passed'] = 'failed', False
        result['error'] = f'{type(error).__name__}: {error}'
        write_json(REPORT, result)
        print(json.dumps({'status': 'failed', 'error': result['error']}, ensure_ascii=False), file=sys.stderr)
        return 1
    write_json(REPORT, result)
    print(json.dumps({key: result[key] for key in ('status', 'compiler', 'quality_steps',
          'assessment_steps', 'compilations', 'runtime_cases', 'subset_checks', 'context_evidence_checks')},
          ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
