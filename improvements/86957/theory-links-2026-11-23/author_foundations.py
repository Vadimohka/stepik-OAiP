def main():
    manifest = json.loads((ROOT/'courses/86957/manifest.json').read_bytes())
    bindings = {b['step_id']: b for b in manifest['step_files']['bindings']}
    rows = []
    for sid, summary in SUMMARIES.items():
        relative = bindings[sid]['path']
        source = subprocess.check_output(['git', 'show', f'{BASE}:courses/86957/{relative}'], cwd=ROOT)
        step = json.loads(source)
        old_text = step['block']['text']
        step['block']['text'] = edit(sid, old_text)
        assert re.findall(r'<pre\b[^>]*>.*?</pre>', old_text, re.S) == re.findall(
            r'<pre\b[^>]*>.*?</pre>', step['block']['text'], re.S), 'Code changed'
        target = PKG/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(step, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
        if sid == 3237989:
            sources = [
                'https://timsong-cpp.github.io/cppwp/n4659/basic.start.static',
                'https://timsong-cpp.github.io/cppwp/n4659/stmt.dcl',
                'https://timsong-cpp.github.io/cppwp/n4861/stmt.dcl',
                'https://timsong-cpp.github.io/cppwp/n4861/basic.start.dynamic',
                'https://gcc.gnu.org/onlinedocs/gcc-14.3.0/gccint/Initialization.html',
            ]
        elif sid == 3238004:
            sources = ['https://timsong-cpp.github.io/cppwp/n4659/basic.start.main',
                       'https://timsong-cpp.github.io/cppwp/n4861/basic.start.main']
        else:
            sources = ['https://cmake.org/cmake/help/v3.22/manual/cmake.1.html',
                       'https://gcc.gnu.org/onlinedocs/gcc/Overall-Options.html']
        rows.append({'step_id': sid, 'path': relative, 'summary': summary,
                     'sources': sources, 'plan': ['LINKS', 'T1']})
    (PKG/'changes_foundations.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps({'part': 'foundations', 'changed_steps': len(rows), 'code_changed': False}))


if __name__ == '__main__':
    main()
