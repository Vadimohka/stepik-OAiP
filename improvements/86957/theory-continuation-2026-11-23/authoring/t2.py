#!/usr/bin/env python3
"""Reproducible T2 editorial sources; only block.text differs from pinned main."""
from pathlib import Path
import copy, hashlib, html, json, re, subprocess, textwrap

ROOT = Path(__file__).resolve().parents[4]
PKG = Path(__file__).resolve().parents[1]
BASE = 'd96e5b9cffa65010c53894a9b65b1a497cb6b58a'
LESSONS = [763630,763639,763640,763642,763719,763644,763646,770585,770586,770587,770588,770589]
ORIGINAL = {}
PATHS = {}
for lesson in LESSONS:
    for path in sorted((ROOT/f'courses/86957/steps/{lesson}').glob('*_text.step')):
        rel = path.relative_to(ROOT)
        data = json.loads(subprocess.check_output(['git','show',f'{BASE}:{rel.as_posix()}'],cwd=ROOT))
        sid = int(data['id'])
        ORIGINAL[sid] = data
        PATHS[sid] = Path('steps')/str(lesson)/path.name

CHANGES = []
TEXTS = {}
PROGRAMS = []
def h(title): return f'<h2>{title}</h2>\n'
def sub(title): return f'<h3>{title}</h3>\n'
def p(text): return f'<p>{text}</p>\n'
def table(headers, rows):
    return '<table><thead><tr>'+''.join(f'<th>{c}</th>' for c in headers)+'</tr></thead><tbody>'+''.join('<tr>'+''.join(f'<td>{c}</td>' for c in row)+'</tr>' for row in rows)+'</tbody></table>\n'
def code(source, lang='cpp'):
    return f'<pre><code class="language-{lang}">'+html.escape(textwrap.dedent(source).strip()+'\n',quote=False)+'</code></pre>\n'
def fragment(source, note='Фрагмент внутри функции; это не отдельная программа.',lang='cpp'):
    return p('<strong>'+html.escape(note)+'</strong>')+code(source,lang)
def program(sid, name, source, cases, lang='cpp', note='Полная программа C++17/C++20.'):
    source=textwrap.dedent(source).strip()+'\n'
    PROGRAMS.append({'step_id':sid,'file':name+('.c' if lang=='c' else '.cpp'),'language':lang,'source':source,'cases':cases})
    return p('<strong>'+note+'</strong>')+code(source,lang)
def case(inp='',out='',rc=0,err=''):
    return {'stdin':inp,'stdout':out,'returncode':rc,'stderr':err}
def refs(*sections,version='n4659'):
    return [f'https://timsong-cpp.github.io/cppwp/{version}/{s}' for s in sections]
def put(sid, summary, body, sources, scope=False):
    assert sid not in TEXTS
    assert body != ORIGINAL[sid]['block']['text']
    TEXTS[sid]=body
    CHANGES.append({'step_id':sid,'path':PATHS[sid].as_posix(),'summary':summary,'sources':sources,'plan':['T2','LINKS']+(['SCOPE'] if scope else [])})
def link(lesson, step, label):
    return f'<a href="https://stepik.org/lesson/{lesson}/step/{step}?unit=">{label}</a>'.replace('?unit=','')
def adapted(sid,replacements,summary,sources,existing_cases=None,extra=''):
    body=ORIGINAL[sid]['block']['text']
    for old,new in replacements:
        assert old in body,(sid,old)
        body=body.replace(old,new)
    body+=extra
    if existing_cases is not None:
        full=[html.unescape(s) for s in re.findall(r'<pre><code(?: class="language-cpp")?>(.*?)</code></pre>',body,re.S) if 'int main(' in html.unescape(s)]
        assert len(full)==len(existing_cases),(sid,len(full),len(existing_cases))
        for i,(source,cases) in enumerate(zip(full,existing_cases),1):
            PROGRAMS.append({'step_id':sid,'file':f'preserved_{sid}_{i}.cpp','language':'cpp','source':source,'cases':cases})
    put(sid,summary,body,sources,scope=True)

