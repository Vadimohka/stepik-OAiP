def main():
    import argparse
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='check exact generated assets without writing')
    args=parser.parse_args()
    outputs=generated_files()
    mismatches=[]
    for relative,content in outputs.items():
        target=PKG/relative
        if args.check:
            if not target.exists() or target.read_text()!=content:
                mismatches.append(relative.as_posix())
        else:
            target.parent.mkdir(parents=True,exist_ok=True)
            target.write_text(content)
    if mismatches:
        raise SystemExit('Generated T2 assets differ: '+', '.join(mismatches))
    print(json.dumps({'mode':'check' if args.check else 'write','reviewed':len(ORIGINAL),'changed':len(TEXTS),'preserved':len(PRESERVED),'programs':len(PROGRAMS),'generated_files':len(outputs)},ensure_ascii=False))

if __name__=='__main__':
    main()
